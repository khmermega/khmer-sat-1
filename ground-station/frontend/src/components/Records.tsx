import { useMemo, useState } from "react";
import { createPortal } from "react-dom";
import { api, type CommandItem, type EventItem, type ImageItem, type Severity } from "../api";
import { bytes, fmt, SEVERITY_STYLE, STATUS_STYLE, utcTime } from "../format";
import { Button, Chip, Panel } from "./Panel";

const SOURCE_LABEL: Record<ImageItem["source"], { text: string; cls: string }> = {
  SIMULATED_ORBITAL: { text: "SIMULATED", cls: "text-gold bg-gold/10 ring-gold/40" },
  GROUND_TEST_HARDWARE: { text: "GROUND TEST", cls: "text-sky bg-sky/10 ring-sky/40" },
  MOCK_SAMPLE: { text: "SAMPLE", cls: "text-violet bg-violet/10 ring-violet/40" },
};

// ---------------------------------------------------------------- gallery
export function ImageGallery({ images }: { images: ImageItem[] }) {
  const [open, setOpen] = useState<ImageItem | null>(null);
  return (
    <Panel testId="gallery" title="Image gallery" subtitle={`${images.length} images received · SHA-256 verified on ground`}>
      {images.length === 0 ? (
        <div className="flex h-40 items-center justify-center text-xs text-ink-3">No images yet — capture one from the camera panel.</div>
      ) : (
        <div className="scroll-thin grid max-h-[22rem] grid-cols-2 gap-3 overflow-y-auto pr-1 sm:grid-cols-3 lg:grid-cols-4">
          {images.map((im) => {
            const src = SOURCE_LABEL[im.source];
            return (
              <button key={im.id} onClick={() => setOpen(im)} className="group overflow-hidden rounded-lg bg-deck text-left ring-1 ring-line transition hover:ring-gold/60">
                <div className="relative aspect-[4/3] overflow-hidden bg-void">
                  <img src={`/api/images/${im.id}/thumbnail`} alt={`Image ${im.id.slice(0, 8)}`} loading="lazy" className="h-full w-full object-cover transition group-hover:scale-105" />
                  <Chip className={`absolute left-1.5 top-1.5 ${src.cls}`}>{src.text}</Chip>
                </div>
                <div className="px-2 py-1.5 font-mono text-[10px] tabular">
                  <div className="flex justify-between text-ink">
                    <span>{im.id.slice(0, 8)}</span>
                    <span className="text-ink-3">{bytes(im.size_bytes)}</span>
                  </div>
                  <div className="text-ink-3">{utcTime(im.captured_utc, true)}</div>
                </div>
              </button>
            );
          })}
        </div>
      )}
      {/* Portal: the panel's backdrop-filter would otherwise trap position:fixed inside it. */}
      {open && createPortal(<ImageModal image={open} onClose={() => setOpen(null)} />, document.body)}
    </Panel>
  );
}

function ImageModal({ image, onClose }: { image: ImageItem; onClose: () => void }) {
  const m = image.meta as Record<string, unknown>;
  const rows: [string, string][] = [
    ["Image ID", image.id],
    ["Provenance", image.source],
    ["Camera", image.camera],
    ["Captured (UTC)", utcTime(image.captured_utc, true)],
    ["Received (UTC)", utcTime(image.received_utc, true)],
    ["Resolution", `${image.width} × ${image.height}`],
    ["JPEG quality", String(m.jpeg_quality ?? "—")],
    ["Size", bytes(image.size_bytes)],
    ["Position", m.lat_deg != null ? `${fmt(m.lat_deg as number, 3, "°")}, ${fmt(m.lon_deg as number, 3, "°")} @ ${fmt(m.alt_km as number, 1, " km")}` : "no GNSS fix"],
    ["Onboard mode", String(m.mode ?? "—")],
    ["Downlink chunks", String(m.chunks ?? "—")],
    ["SHA-256", image.sha256],
    ["Integrity", image.verified ? "verified on ground" : "NOT verified"],
  ];
  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-void/85 p-4 backdrop-blur-sm" onClick={onClose} role="dialog" aria-modal="true">
      <div className="grid max-h-[92vh] w-full max-w-6xl overflow-hidden rounded-xl border border-line-2 bg-panel shadow-2xl lg:grid-cols-[1fr_22rem]" onClick={(e) => e.stopPropagation()}>
        <div className="flex min-h-0 items-center justify-center bg-void">
          <img src={`/api/images/${image.id}/file`} alt="Full resolution capture" className="max-h-[92vh] w-full object-contain" />
        </div>
        <div className="scroll-thin overflow-y-auto p-4">
          <div className="flex items-center justify-between">
            <h3 className="text-sm font-semibold text-ink">Capture metadata</h3>
            <Button variant="ghost" onClick={onClose}>
              ✕
            </Button>
          </div>
          {image.source === "SIMULATED_ORBITAL" && (
            <p className="mt-2 rounded-md bg-gold/10 px-2 py-1.5 text-[11px] text-gold ring-1 ring-gold/30">Synthetic scene generated by the simulator — not real Earth observation imagery.</p>
          )}
          <dl className="mt-3 space-y-2">
            {rows.map(([k, v]) => (
              <div key={k}>
                <dt className="text-[10px] uppercase tracking-wider text-ink-3">{k}</dt>
                <dd className="break-all font-mono text-[11px] text-ink">{v}</dd>
              </div>
            ))}
          </dl>
          <a href={`/api/images/${image.id}/file`} download={`khmersat1-${image.id}.jpg`} className="mt-4 inline-block text-xs text-sky hover:underline">
            Download JPEG
          </a>
        </div>
      </div>
    </div>
  );
}

// ---------------------------------------------------------------- events
export function EventsPanel({ events, role, onAck }: { events: EventItem[]; role: string | null; onAck: () => void }) {
  const [filter, setFilter] = useState<Severity | "ALARMS" | "ALL">("ALL");
  const list = useMemo(
    () => events.filter((e) => filter === "ALL" || (filter === "ALARMS" ? e.severity !== "INFO" : e.severity === filter)).slice(0, 200),
    [events, filter],
  );
  const unacked = events.filter((e) => e.severity === "CRITICAL" && !e.acknowledged).length;
  const ack = async (id: string) => {
    try {
      await api.ackEvent(id);
      onAck();
    } catch {
      /* ignored - shown as still unacknowledged */
    }
  };
  return (
    <Panel
      testId="events"
      title="Events & alarms"
      subtitle={unacked ? <span className="text-crit">{unacked} unacknowledged critical alarm{unacked > 1 ? "s" : ""}</span> : "space + ground events"}
      actions={
        <div className="flex rounded-lg bg-deck p-0.5 ring-1 ring-line">
          {(["ALL", "ALARMS", "CRITICAL"] as const).map((f) => (
            <button key={f} onClick={() => setFilter(f)} className={`rounded-md px-2 py-1 text-[10px] ${filter === f ? "bg-sky/20 text-sky" : "text-ink-2"}`}>
              {f}
            </button>
          ))}
        </div>
      }
      bodyClassName="p-0"
    >
      <ul className="scroll-thin max-h-[26rem] divide-y divide-line/60 overflow-y-auto">
        {list.map((e) => (
          <li key={e.id} className={`flex gap-3 px-4 py-2 ${e.severity === "CRITICAL" && !e.acknowledged ? "bg-crit/5" : ""}`}>
            <span className="w-16 shrink-0 pt-0.5 font-mono text-[10px] tabular text-ink-3">{utcTime(e.utc)}</span>
            <div className="min-w-0 flex-1">
              <div className="flex flex-wrap items-center gap-1.5">
                <Chip className={SEVERITY_STYLE[e.severity]}>{e.severity}</Chip>
                <span className="font-mono text-[11px] text-ink">{e.code}</span>
                <span className="text-[10px] text-ink-3">
                  {e.origin === "space" ? "▲" : "▼"} {e.source}
                </span>
              </div>
              <p className="mt-0.5 break-words text-[11px] text-ink-2">{e.message}</p>
            </div>
            {e.severity !== "INFO" &&
              (e.acknowledged ? (
                <span className="shrink-0 self-center text-[10px] text-ink-3">ack · {e.acknowledged_by}</span>
              ) : (
                <Button variant="ghost" className="shrink-0 self-center !px-2 !py-1 text-[10px]" disabled={!role} onClick={() => ack(e.id)}>
                  ACK
                </Button>
              ))}
          </li>
        ))}
        {list.length === 0 && <li className="px-4 py-6 text-center text-xs text-ink-3">No events</li>}
      </ul>
    </Panel>
  );
}

// ---------------------------------------------------------------- audit
export function CommandHistory({ commands }: { commands: CommandItem[] }) {
  const list = commands.filter((c) => !c.automatic).slice(0, 100);
  return (
    <Panel testId="audit" title="Command history · audit trail" subtitle="Every telecommand with operator, sequence number and onboard acknowledgement" bodyClassName="p-0">
      <div className="scroll-thin max-h-[22rem] overflow-auto">
        <table className="w-full min-w-[760px] text-left text-[11px]">
          <thead className="sticky top-0 bg-panel-2 text-[10px] uppercase tracking-wider text-ink-3">
            <tr>
              {["Sent (UTC)", "Command", "Args", "Operator", "Seq", "Status", "Reason / result", "Ack (UTC)"].map((h) => (
                <th key={h} className="px-3 py-2 font-semibold">
                  {h}
                </th>
              ))}
            </tr>
          </thead>
          <tbody className="divide-y divide-line/60 font-mono tabular">
            {list.map((c) => (
              <tr key={c.id} className="hover:bg-panel-2/50">
                <td className="whitespace-nowrap px-3 py-1.5 text-ink-3">{utcTime(c.created_utc, true)}</td>
                <td className="whitespace-nowrap px-3 py-1.5 text-ink">
                  {c.critical && <span className="mr-1 text-crit">⚠</span>}
                  {c.type}
                </td>
                <td className="max-w-[14rem] truncate px-3 py-1.5 text-ink-2" title={JSON.stringify(c.args)}>
                  {Object.keys(c.args).length ? JSON.stringify(c.args) : "—"}
                </td>
                <td className="px-3 py-1.5 text-ink-2">{c.operator}</td>
                <td className="px-3 py-1.5 text-ink-3">{c.seq ?? "—"}</td>
                <td className="px-3 py-1.5">
                  <Chip className={STATUS_STYLE[c.status] ?? STATUS_STYLE.SENT}>{c.status}</Chip>
                </td>
                <td className="max-w-[18rem] truncate px-3 py-1.5 text-ink-2" title={c.reason || JSON.stringify(c.detail)}>
                  {c.reason || (Object.keys(c.detail).length ? JSON.stringify(c.detail) : "—")}
                </td>
                <td className="whitespace-nowrap px-3 py-1.5 text-ink-3">{utcTime(c.ack_utc)}</td>
              </tr>
            ))}
            {list.length === 0 && (
              <tr>
                <td colSpan={8} className="px-3 py-6 text-center text-ink-3">
                  No commands sent yet
                </td>
              </tr>
            )}
          </tbody>
        </table>
      </div>
    </Panel>
  );
}
